"""Regenerates src/Xsl3/Resources/Strings.resx and SR.g.cs.

Upstream System.Private.Xml generates its SR class from Strings.resx at build time. Xsl3 keeps a
pruned copy instead: every SR.<Name> used under src/Xsl3 is taken from eng/Strings.upstream.resx
(the full upstream file) or, for Xsl3-only strings, from eng/Strings.xsl3.resx.

    py eng/gen-sr.py
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "Xsl3"
OUT = SRC / "Resources"
NOT_STRINGS = {"Format", "GetResourceString", "UsingResourceKeys", "ResourceManager"}


def load(path):
    if not path.exists():
        return {}
    return {d.get("name"): d.findtext("value") or "" for d in ET.parse(path).getroot().findall("data")}


def main():
    upstream = load(ROOT / "eng" / "Strings.upstream.resx")
    local = load(ROOT / "eng" / "Strings.xsl3.resx")
    used = set()
    for cs in SRC.rglob("*.cs"):
        if "obj" in cs.parts or "bin" in cs.parts or cs.name == "SR.g.cs":
            continue
        for line in cs.read_text(encoding="utf-8").splitlines():
            code = line.split("//", 1)[0]
            # Resource names are PascalCase; this skips a local string named SR in XPathConvert.cs.
            used.update(re.findall(r"\bSR\.([A-Z][A-Za-z0-9_]*)", code))
    used -= NOT_STRINGS

    missing = sorted(n for n in used if n not in upstream and n not in local)
    if missing:
        sys.exit("unknown SR names: " + ", ".join(missing))

    names = sorted(used)
    OUT.mkdir(exist_ok=True)
    with open(OUT / "Strings.resx", "w", encoding="utf-8", newline="\n") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by eng/gen-sr.py. Do not edit. -->\n<root>\n')
        f.write('  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>\n')
        f.write('  <resheader name="version"><value>2.0</value></resheader>\n')
        f.write('  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>\n')
        f.write('  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>\n')
        for n in names:
            v = local.get(n, upstream.get(n))
            f.write(f'  <data name="{n}" xml:space="preserve">\n    <value>{escape(v)}</value>\n  </data>\n')
        f.write("</root>\n")

    with open(OUT / "SR.g.cs", "w", encoding="utf-8", newline="\n") as f:
        f.write("// <auto-generated>Generated by eng/gen-sr.py from Resources/Strings.resx. Do not edit.</auto-generated>\n\n")
        f.write("#nullable enable\n\nusing System.Resources;\n\nnamespace System\n{\n    internal static partial class SR\n    {\n")
        f.write("        private static ResourceManager? s_resourceManager;\n")
        f.write('        internal static ResourceManager ResourceManager => s_resourceManager ??= new ResourceManager("Xsl3.Resources.Strings", typeof(SR).Assembly);\n\n')
        for n in names:
            f.write(f'        internal static string @{n} => GetResourceString("{n}");\n')
        f.write("    }\n}\n")
    print(f"{len(names)} strings")


if __name__ == "__main__":
    main()
