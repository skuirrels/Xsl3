#!/usr/bin/env bash
# Assembles the W3C harness reports (tests/Xsl3.W3C/bin/<configuration>/<tfm>/w3c-reports) into
# docs/conformance-sets.md: pass rates per test set and per spec and feature (remaining-scope 8.5).
# Usage: eng/conformance-report.sh [reports-dir] [output]. CI writes it to the job summary and an artifact.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
REPORTS="${1:-$ROOT/tests/Xsl3.W3C/bin/Release/net10.0/w3c-reports}"
OUT="${2:-$ROOT/docs/conformance-sets.md}"

section() { # title, report file: the report without its failure list, its headings one level down
  local file="$REPORTS/$2"
  [ -f "$file" ] || return 0
  echo "## $1"
  echo
  awk '/^## Failures/ { exit } /^# / { print "**" substr($0, 3) "**"; next } { print }' "$file"
}

{
  echo "# Conformance by test set"
  echo
  echo "Generated by \`eng/conformance-report.sh\` from the W3C harness reports; don't edit by hand."
  echo "docs/conformance.md has the history. Regression baselines are in \`tests/Xsl3.W3C/baselines\`; current failures are in the raw harness reports."
  echo "A test counts under each spec and feature it or its test set depends on."
  echo
  section "XSLT 3.0 profile (xslt30-test)" xslt30-run.md
  section "XSLT 2.0 profile (xslt30-test)" xslt30-run-2.0.md
  section "P7 streaming development (unstreamed execution)" xslt30-run-strm.md
  section "P7 streaming development (strict forward inputs; incomplete)" xslt30-run-strm-strict.md
  section "P7 posture and sweep analysis" xslt30-run-sandp.md
  section "XPath 3.1 evaluation (QT3)" qt3-run.md
  section "XPath 3.1 parsing (QT3)" qt3-parse.md
} > "$OUT"
echo "$OUT"
