"""Generates src/Xsl3/XPath31/Functions/CaseMapping.g.cs: Unicode full case mappings (UnicodeData plus the
unconditional SpecialCasing entries) for fn:upper-case and fn:lower-case, from Python's Unicode database.

    py eng/gen-casing.py
"""
import pathlib, sys, unicodedata

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "src/Xsl3/XPath31/Functions/CaseMapping.g.cs"

def table(fn):
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        m = fn(c)
        if m != c:
            rows.append((cp, m))
    return rows

def lit(s):
    bs = chr(92)
    return '"' + ''.join(bs + ('u%04X' % ord(ch) if ord(ch) < 0x10000 else 'U%08X' % ord(ch)) for ch in s) + '"'

def emit(name, rows):
    keys = ', '.join('0x%X' % cp for cp, _ in rows)
    values = ', '.join(lit(m) for _, m in rows)
    return f"""        private static readonly int[] s_{name}Keys = {{ {keys} }};

        private static readonly string[] s_{name}Values = {{ {values} }};
"""

upper = table(str.upper)
lower = table(str.lower)
src = f"""// Licensed under the MIT license. See LICENSE.TXT in the repository root.
// <auto-generated> by eng/gen-casing.py from Unicode {unicodedata.unidata_version}; do not edit. </auto-generated>

namespace Xsl3.XPath31.Functions
{{
    internal static partial class CaseMapping
    {{
{emit("upper", upper)}
{emit("lower", lower)}    }}
}}
"""
out.write_text(src, encoding="utf-8", newline="\n")
print(f"{len(upper)} upper, {len(lower)} lower mappings (Unicode {unicodedata.unidata_version})")
