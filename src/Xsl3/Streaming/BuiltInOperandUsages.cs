/// <summary>
/// Operand roles transcribed from XSLT 3.0 Recommendation (8 June 2017), §19.8.9:
/// https://www.w3.org/TR/xslt-30/#classifying-built-in-functions
/// These are language rules, not function signatures. Signatures come from FunctionLibrary and
/// XPath31Compiler.CompiledFunctionSignature. The 18 special rules are in ExpressionAnalysis.Functions.
/// The short fn:error entries in the Recommendation contain malformed equivalences. For #1/#2,
/// apply the roles of their supplied arguments from #3; the runtime does not put streamed nodes
/// in an omitted error object (F&amp;O 3.1 §2.3.1 permits an implementation-dependent error object).
/// </summary>
internal static class BuiltInOperandUsages
{
    private static readonly Dictionary<(string Ns, string Local, int Arity), IReadOnlyList<OperandUsage>> s_roles = Read();

    internal static IReadOnlyList<OperandUsage>? Find(QName name, int arity)
    {
        // concat is variadic: every argument is absorbed, for every supported arity.
        if (name.NamespaceUri == QName.Ns.Fn && name.LocalName == "concat" && arity >= 2)
            return Array.AsReadOnly(Enumerable.Repeat(OperandUsage.Absorption, arity).ToArray());
        return s_roles.GetValueOrDefault((name.NamespaceUri, name.LocalName, arity));
    }

    private static Dictionary<(string, string, int), IReadOnlyList<OperandUsage>> Read()
    {
        var roles = new Dictionary<(string, string, int), IReadOnlyList<OperandUsage>>();
        foreach (string line in Table.Split('\n', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries))
        {
            int colon = line.IndexOf(':'), open = line.IndexOf('(');
            string ns = ExpressionAnalysisOptions.StandardNamespace(line[..colon])!;
            string arguments = line[(open + 1)..^1];
            string[] values = arguments.Length == 0 ? Array.Empty<string>() : arguments.Split(", ");
            OperandUsage[] usages = System.Array.ConvertAll(values, v => v switch
            {
                "A" => OperandUsage.Absorption, "I" => OperandUsage.Inspection,
                "T" => OperandUsage.Transmission, "N" => OperandUsage.Navigation,
                _ => throw new InvalidOperationException("Unknown spec operand role: " + v),
            });
            roles.Add((ns, line[(colon + 1)..open], usages.Length), Array.AsReadOnly(usages));
        }
        return roles;
    }

